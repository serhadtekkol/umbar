import AppKit
import os

/// The slice of `NSPasteboard` the monitor uses. Exists so the
/// classification and read-policy logic can be exercised against a
/// private, uniquely named pasteboard (which is not subject to pasteboard
/// privacy) instead of the user's general pasteboard.
protocol PasteboardSource: AnyObject {
    var changeCount: Int { get }
    var types: [NSPasteboard.PasteboardType]? { get }
    var accessBehavior: NSPasteboard.AccessBehavior { get }
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
}

extension NSPasteboard: PasteboardSource {}

/// What the monitor observed for one pasteboard change.
enum ClipboardEvent: Equatable, Sendable {
    /// Plain text was read. `text` is user content: never log it.
    case captured(text: String, changeCount: Int)
    /// The writer marked the content as sensitive or short-lived
    /// (nspasteboard.org conventions, BR-4.3); contents were not read.
    case skippedSensitive(marker: String, changeCount: Int)
    /// The change carried no plain-text representation (v1 text-only spike).
    case skippedNonText(changeCount: Int)
    /// Reading would surface the system pasteboard alert, or the user chose
    /// "Deny"; contents were not read. Drives the AC-4.8 "permission
    /// required" state.
    case permissionRequired(behavior: NSPasteboard.AccessBehavior, changeCount: Int)
}

/// Polls the general pasteboard's `changeCount` and reads new text only
/// when doing so cannot raise the macOS pasteboard privacy alert.
///
/// Why polling: AppKit has no change notification for the general
/// pasteboard. Measured on macOS 27.0.1 with privacy enforced (spike A2):
/// `changeCount`, `types`, `detectedPatterns` and `detectedMetadata` never
/// raise the privacy alert; `string(forType:)` does, and blocks the reading
/// thread until the user answers. Other content reads (`data(forType:)`,
/// `readObjects`, `detectedValues`) were not measured and are assumed to
/// behave like `string(forType:)`.
///
/// Threading: main actor only. This is not a style choice. With pasteboard
/// privacy enforced, `NSPasteboard.accessBehavior` is answered by AppKit's
/// TrustedUIService over a run-loop semaphore and asserts (SIGABRT,
/// `-[HIRunLoopSemaphore wait:]`) when called off the main thread. On a
/// stock 27.0.1 machine enforcement is off and the getter is a constant, so
/// a background-queue version passes every test and then crashes the day
/// Apple flips the switch. Spike A2 reproduced exactly that.
@MainActor
final class ClipboardMonitor {

    /// When the monitor is allowed to read pasteboard contents.
    enum ReadPolicy: Sendable {
        /// Read only when the user has set "Allow" for this app in
        /// System Settings > Privacy & Security > Paste from Other Apps
        /// (`accessBehavior == .alwaysAllow`).
        /// In every other state, emit `.permissionRequired` instead. This
        /// is the production policy: a background monitor must never be the
        /// thing that pops the system alert while the user is busy elsewhere.
        case onlyWhenAlwaysAllowed
        /// Read regardless of `accessBehavior`. Only for the spike harness,
        /// to observe what the system does on an unattended read. Under
        /// enforcement this blocks the main thread until the user answers
        /// the alert; never use it in the app.
        case always
    }

    /// Type markers that mean "do not record this" (BR-4.3, AC-4.4).
    /// Source: http://nspasteboard.org — the de-facto convention used by
    /// 1Password, Bitwarden, KeePassXC, Keychain Access, TextExpander and
    /// clipboard managers. The legacy identifiers are still written by
    /// older apps, so they stay until someone shows they are dead.
    nonisolated static let sensitivityMarkers: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"),
    ]

    /// Returns the first sensitivity marker present in `types`, or `nil`
    /// when the content may be recorded. Pure; safe to call from anywhere.
    nonisolated static func sensitivityMarker(in types: [NSPasteboard.PasteboardType]) -> NSPasteboard.PasteboardType? {
        let present = Set(types)
        return sensitivityMarkers.first { present.contains($0) }
    }

    private let source: PasteboardSource
    private let interval: DispatchTimeInterval
    private let leeway: DispatchTimeInterval
    private let policy: ReadPolicy
    private let onEvent: (ClipboardEvent) -> Void
    private let log = Logger(subsystem: "umbar", category: "ClipboardMonitor")

    private var timer: DispatchSourceTimer?
    private var lastChangeCount: Int

    /// - Parameters:
    ///   - source: Pasteboard to watch; production passes `NSPasteboard.general`.
    ///   - interval: Poll period. 0.5 s keeps AC-4.1 (visible within 2 s)
    ///     with a wide margin; see the spike doc for its CPU cost.
    ///   - leeway: Timer slack granted to the kernel so wakeups coalesce
    ///     with other timers. Larger is cheaper; it adds directly to latency.
    ///   - policy: See `ReadPolicy`.
    ///   - onEvent: Called synchronously on the main actor, once per
    ///     observed change.
    init(
        source: PasteboardSource = NSPasteboard.general,
        interval: DispatchTimeInterval = .milliseconds(500),
        leeway: DispatchTimeInterval = .milliseconds(100),
        policy: ReadPolicy = .onlyWhenAlwaysAllowed,
        onEvent: @escaping (ClipboardEvent) -> Void
    ) {
        self.source = source
        self.interval = interval
        self.leeway = leeway
        self.policy = policy
        self.onEvent = onEvent
        // Seed with the current count so whatever was already on the
        // pasteboard at launch is not reported as a fresh copy.
        self.lastChangeCount = source.changeCount
    }

    isolated deinit {
        timer?.cancel()
    }

    var isRunning: Bool { timer != nil }

    /// Starts polling. Idempotent.
    func start() {
        guard timer == nil else { return }
        let t = DispatchSource.makeTimerSource(queue: .main)
        t.schedule(deadline: .now() + interval, repeating: interval, leeway: leeway)
        t.setEventHandler { [weak self] in
            MainActor.assumeIsolated { _ = self?.tick() }
        }
        timer = t
        t.resume()
    }

    /// Stops polling. Idempotent.
    func stop() {
        timer?.cancel()
        timer = nil
    }

    /// One poll. Internal so the harness can drive it deterministically
    /// without a timer.
    @discardableResult
    func tick() -> ClipboardEvent? {
        let count = source.changeCount
        guard count != lastChangeCount else { return nil }
        lastChangeCount = count

        let event = classify(changeCount: count)
        if let event {
            log.debug("change \(count, privacy: .public): \(Self.describe(event), privacy: .public)")
            onEvent(event)
        }
        return event
    }

    private func classify(changeCount count: Int) -> ClipboardEvent? {
        let types = source.types ?? []

        // Checked before any content read: a concealed item must not be
        // read at all, not merely dropped after reading.
        if let marker = Self.sensitivityMarker(in: types) {
            return .skippedSensitive(marker: marker.rawValue, changeCount: count)
        }
        guard types.contains(.string) else {
            return .skippedNonText(changeCount: count)
        }

        let behavior = source.accessBehavior
        if policy == .onlyWhenAlwaysAllowed, behavior != .alwaysAllow {
            return .permissionRequired(behavior: behavior, changeCount: count)
        }

        guard let text = source.string(forType: .string) else {
            // A nil read with `.string` advertised means the system refused
            // the read (deny, or the alert was dismissed with "Don't Allow").
            return .permissionRequired(behavior: source.accessBehavior, changeCount: count)
        }

        // The pasteboard may have changed while we were reading; that change
        // is picked up on the next tick, and this read belongs to neither
        // generation reliably, so drop it.
        guard source.changeCount == count else { return nil }
        return .captured(text: text, changeCount: count)
    }

    /// Content-free description for logs.
    nonisolated static func describe(_ event: ClipboardEvent) -> String {
        switch event {
        case .captured(let text, _): return "captured(len=\(text.count))"
        case .skippedSensitive(let marker, _): return "skippedSensitive(\(marker))"
        case .skippedNonText: return "skippedNonText"
        case .permissionRequired(let b, _): return "permissionRequired(behavior=\(b.rawValue))"
        }
    }
}
