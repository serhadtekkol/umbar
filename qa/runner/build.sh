#!/bin/zsh
# Builds UmbarQARunner.app and qa-cli (docs/qa-gui-runner.md §3, card #96).
#
# usage: UMBAR_QA_TARGET_UID=<uid> build.sh <output-dir>
#
# Environment:
#   UMBAR_QA_TARGET_UID     required. UID of the `umbarqa` account on the Air
#                           (`id -u umbarqa` there). Embedded in the binary;
#                           the runner refuses to start under any other UID.
#                           0 and 501 (the owner's account) are refused here.
#   UMBAR_QA_LIFETIME_DAYS  optional, 1..14, default 14. The embedded expiry
#                           is build time + this many days (§3.2 rule 5).
#   CODE_SIGN_IDENTITY      optional, default "-" (ad-hoc, development only:
#                           the cdhash and thus the TCC identity change on
#                           every build, see README "Signing"). For a build
#                           that is granted anything, pass
#                           CODE_SIGN_IDENTITY="Developer ID Application".
#   NOTARY_PROFILE          optional. A `notarytool store-credentials` profile;
#                           when set (and the identity is not ad-hoc) the app
#                           is notarized and stapled.
#
# The stamp is compiled from a staging copy of the package: the committed
# Sources/QARunnerStamp/BuildStamp.swift stays unstamped and the worktree is
# never modified. Hardened Runtime is always on, and no entitlements file
# exists or is passed (§3.1: empty entitlements).
#
# Not an Xcode target on purpose (design §7): the runner must not share
# umbar's pbxproj, signing settings or entitlements.
set -euo pipefail

here=${0:A:h}
outdir=${1:?usage: UMBAR_QA_TARGET_UID=<uid> build.sh <output-dir>}
uid=${UMBAR_QA_TARGET_UID:?set UMBAR_QA_TARGET_UID to the uid of umbarqa on the Air}
identity=${CODE_SIGN_IDENTITY:--}
days=${UMBAR_QA_LIFETIME_DAYS:-14}

[[ $uid == <-> ]] || { print -u2 "UMBAR_QA_TARGET_UID must be a number"; exit 64 }
(( uid != 0 && uid != 501 )) || { print -u2 "refusing to stamp uid $uid (root / owner account)"; exit 64 }
[[ $days == <-> ]] && (( days >= 1 && days <= 14 )) || { print -u2 "UMBAR_QA_LIFETIME_DAYS must be 1..14"; exit 64 }

built=$(date +%s)
expires=$(( built + days * 86400 ))

stage=$(mktemp -d "${TMPDIR:-/tmp}/qarunner-stage.XXXXXX")
trap 'rm -rf "$stage"' EXIT
rsync -a --exclude .build --exclude .swiftpm "$here/" "$stage/"
cat > "$stage/Sources/QARunnerStamp/BuildStamp.swift" <<EOF
// Generated by build.sh at $(date -u -r $built +%Y-%m-%dT%H:%M:%SZ). Not committed.
public enum BuildStamp {
    public static let targetUID: UInt32? = $uid
    public static let targetUserName = "umbarqa"
    public static let builtAt: Int64? = $built
    public static let expiresAt: Int64? = $expires
}
EOF

swift build -c release --package-path "$stage" --product UmbarQARunner
swift build -c release --package-path "$stage" --product qa-cli
bin=$(swift build -c release --package-path "$stage" --show-bin-path)

# Binary-level check of §3.2 rules 1-3 and §5 "nm -u ... boş". The source
# scan in ForbiddenAPITests is the first line; this catches anything that
# arrives through a dependency or a macro.
forbidden='^_(posix_spawnp?|fork|vfork|system|popen|execv|execve|execvp|execl|execlp|execle|dlopen|dlsym|connect|CGWindowListCreateImage|CGDisplayCreateImage|CGEventKeyboardSetUnicodeString|AXUIElementPerformAction|AXUIElementSetAttributeValue|CFPreferencesSetAppValue|CFPreferencesSetValue)$|NSTask|NSAppleScript|NSUserUnixTask|NSUserAppleScriptTask|NSPasteboard|NSURLSession|Foundation7Process|Foundation10URLSession|nw_listener|nw_connection'
# nm runs on its own line so a failing nm stops the script (set -e) instead
# of reading as "no forbidden symbols".
undefined=$(nm -u "$bin/UmbarQARunner")
[[ -n $undefined ]] || { print -u2 "nm -u returned nothing; refusing to trust the check"; exit 1 }
if print -- "$undefined" | grep -E "$forbidden"; then
    print -u2 "forbidden symbol(s) in UmbarQARunner (see above); not packaging"
    exit 1
fi

app=$outdir/UmbarQARunner.app
mkdir -p "$outdir"
rm -rf "$app"
mkdir -p "$app/Contents/MacOS"
cp "$here/Info.plist" "$app/Contents/Info.plist"
plutil -replace CFBundleVersion -string "$built" "$app/Contents/Info.plist"
cp "$bin/UmbarQARunner" "$app/Contents/MacOS/UmbarQARunner"
cp "$bin/qa-cli" "$outdir/qa-cli"

timestamp=--timestamp
[[ $identity == - ]] && timestamp=--timestamp=none

# No --entitlements: an empty entitlement set is the requirement, and
# codesign without the flag embeds none. The designated requirement is the
# one codesign generates for the identity (see README "Signing").
codesign --force --options runtime $timestamp --identifier com.serhadbahadir.qarunner.cli \
    --sign "$identity" "$outdir/qa-cli"
codesign --force --options runtime $timestamp --identifier com.serhadbahadir.qarunner \
    --sign "$identity" "$app"
codesign --verify --strict --verbose=2 "$app"

ents=$(codesign -d --entitlements - --xml "$app" 2>/dev/null || true)
if [[ -n $ents ]]; then
    print -u2 "entitlements are not empty:"; print -u2 -- "$ents"; exit 1
fi
# Developer ID: flags=0x10000(runtime); ad-hoc: flags=0x10002(adhoc,runtime).
# Captured first: `grep -q` in a pipe would SIGPIPE codesign under pipefail.
sig=$(codesign -dv --verbose=4 "$app" 2>&1)
[[ $sig =~ 'CodeDirectory [^'$'\n'']*flags=0x[0-9a-f]+\([^)]*runtime' ]] \
    || { print -u2 "hardened runtime flag missing"; exit 1 }

if [[ -n ${NOTARY_PROFILE:-} && $identity != - ]]; then
    zip=$outdir/UmbarQARunner.zip
    ditto -c -k --keepParent "$app" "$zip"
    xcrun notarytool submit "$zip" --keychain-profile "$NOTARY_PROFILE" --wait
    xcrun stapler staple "$app"
    rm -f "$zip"
fi

# Build record (test-plan §3.4): Habibe compares the cdhash with
# `qa-cli status` on the Air (§3.3, A3).
record=$outdir/UmbarQARunner.build-record.txt
{
    print "built_at=$(date -u -r $built +%Y-%m-%dT%H:%M:%SZ)"
    print "expires_at=$(date -u -r $expires +%Y-%m-%dT%H:%M:%SZ)"
    print "target_uid=$uid"
    print "git_head=$(git -C "$here" rev-parse HEAD 2>/dev/null || print unknown)"
    print "identity=$identity"
    print -- "$sig" | grep -E '^(Identifier|Authority|TeamIdentifier|CDHash|CodeDirectory)'
    print -n "designated_requirement="; codesign -d -r- "$app" 2>&1 | sed -n 's/^#* *designated => //p'
} > "$record"
cat "$record"
